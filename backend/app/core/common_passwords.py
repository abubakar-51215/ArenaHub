_LEET = str.maketrans(
    {"@": "a", "4": "a", "0": "o", "1": "l", "!": "i", "3": "e", "$": "s", "5": "s", "7": "t"}
)
_NON_LETTERS = re.compile(r"[^a-z]+")


def is_common(password: str) -> bool:
    low = password.lower()
    if low in _BASES:
        return True
    # the same word with digits and symbols swapped in ("p@ssw0rd") and/or added at the end
    # ("password1!")
    swapped = low.translate(_LEET)
    for candidate in (low, swapped):
        letters = _NON_LETTERS.sub("", candidate)
        if letters in _BASES and len(candidate) - len(letters) <= 6:
            return True
    # a few repeated characters ("Aaaaaaa1!")
    return len(set(low)) <= 3
