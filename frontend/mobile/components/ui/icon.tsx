import Svg, { Circle, Ellipse, Path, Rect } from 'react-native-svg';

import { Icons, type IconName } from '@/constants/icons.generated';

export type { IconName };

interface IconProps {
  name: IconName;
  size?: number;
  color?: string;
  /** Overrides the icon's own stroke width (the prototype uses a different
   * value for some instances of the same shape, e.g. the large confirmation
   * tick — see ConfirmTick). Defaults to the icon's own declared width. */
  strokeWidth?: number;
  /** Fills the shapes with this colour (a filled heart); the stroke stays `color`. */
  fill?: string;
}

/**
 * Renders one of the 26 icons ported from the prototype's `I` object
 * (constants/icons.generated.ts, generated by scripts/extract-icons.mjs —
 * never hand-edited). `currentColor` in the source becomes the `color` prop;
 * any shape with its own literal fill/stroke/opacity (none of the 26 do,
 * only the brand mark and glow art) would keep it, but is not expected here.
 */
export function Icon({ name, size, color = '#0F1A15', strokeWidth, fill }: IconProps) {
  const def = Icons[name];
  // Only `search` declares its own width/height in the prototype (15x15);
  // every other icon is sized purely by the `size` prop, defaulting to the
  // viewBox's own square dimension read off viewBox itself.
  const viewBoxSize = Number(def.viewBox.split(' ')[2]);
  const resolvedSize = size ?? (def.width ? Number(def.width) : viewBoxSize);

  return (
    <Svg
      width={resolvedSize}
      height={resolvedSize}
      viewBox={def.viewBox}
      fill={def.fill === 'currentColor' ? color : 'none'}>
      {def.shapes.map((shape, i) => {
        const key = `${name}-${i}`;
        const shapeFill = fill ?? shape.fill ?? (def.fill === 'currentColor' ? color : 'none');
        const common = {
          fill: shapeFill,
          stroke: color,
          strokeWidth: strokeWidth ?? Number(def.strokeWidth ?? 0),
          strokeLinecap: def.strokeLinecap as 'round' | 'butt' | 'square' | undefined,
          strokeLinejoin: def.strokeLinejoin as 'round' | 'miter' | 'bevel' | undefined,
        };
        if (shape.type === 'path') return <Path key={key} d={shape.d!} {...common} />;
        if (shape.type === 'circle')
          return <Circle key={key} cx={Number(shape.cx)} cy={Number(shape.cy)} r={Number(shape.r)} {...common} />;
        if (shape.type === 'rect')
          return (
            <Rect
              key={key}
              x={Number(shape.x)}
              y={Number(shape.y)}
              width={Number(shape.width)}
              height={Number(shape.height)}
              rx={shape.rx ? Number(shape.rx) : undefined}
              {...common}
            />
          );
        if (shape.type === 'ellipse')
          return (
            <Ellipse
              key={key}
              cx={Number(shape.cx)}
              cy={Number(shape.cy)}
              rx={Number(shape.rx)}
              ry={Number(shape.ry)}
              {...common}
            />
          );
        return null;
      })}
    </Svg>
  );
}
